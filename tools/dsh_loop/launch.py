"""Console launchers for the NOVA3 DSH loop (what ``nova3-dsh`` actually is).

The launcher file the installer drops in ``~/.local/bin/nova3-dsh`` (or
``%LOCALAPPDATA%\\Nova3\\bin\\nova3-dsh.cmd``) carries exactly one piece of
machine-specific data: ``[source_checkout, config_path]``. It contains no
secrets and no identity beyond that. Everything else lives in the project
checkout, so updating the checkout (``nova3-dsh update``) updates the loop
itself.
"""

from __future__ import annotations

import json
import os
from pathlib import Path

from . import credentials, resource

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]


def spec_for(state_path: Path) -> list[str | None]:
    """``[checkout_or_None, state_path]`` embedded in every launcher."""
    checkout: str | None = None
    try:
        data = json.loads(state_path.read_text(encoding="utf-8"))
        if isinstance(data, dict) and data.get("workspace"):
            checkout = str(data["workspace"])
    except (OSError, ValueError):
        pass
    return [checkout, str(state_path)]


def _py_probe() -> str:
    """Shell snippet that picks the first usable Python 3.10+ interpreter."""
    return (
        'for c in python3 python py; do\n'
        '  if command -v "$c" >/dev/null 2>&1; then\n'
        '    if "$c" -c "import sys; sys.exit(0 if sys.version_info >= (3,10) else 1)" 2>/dev/null; then\n'
        '      PY="$c"; break\n'
        '    fi\n'
        '  fi\n'
        'done\n'
    )


def unix_launcher_text(state_path: Path) -> str:
    checkout, config = spec_for(state_path)
    repo = checkout or str(REPO)
    return f"""#!/bin/sh
# NOVA3 reconstruction worker -- generated by tools/dsh_loop. Safe to delete.
# Edit nothing here: re-run the installer or use 'nova3-dsh setup' instead.
NOVA3_SPEC='{json.dumps([checkout, config])}'
PY=""
{_py_probe()}
if [ -z "$PY" ]; then
  echo "NOVA3 worker: Python 3.10+ was not found. Install Python and run this again." >&2
  exit 2
fi
cd "{repo}" 2>/dev/null || {{ echo "NOVA3 worker: source checkout missing at {repo}. Run the installer again." >&2; exit 2; }}
exec "$PY" -c 'import sys; sys.path.insert(0, sys.argv[1]); from tools.dsh_loop import cli; raise SystemExit(cli.launcher_main(sys.argv[2], sys.argv[3:]))' \\
  "{repo}" '{json.dumps([checkout, config])}' "$@"
"""


def powershell_launcher_text(state_path: Path) -> str:
    checkout, config = spec_for(state_path)
    repo = checkout or str(REPO)
    payload = json.dumps([checkout, config])
    return f"""# NOVA3 reconstruction worker -- generated by tools/dsh_loop. Safe to delete.
$ErrorActionPreference = 'Stop'
$Spec = '{payload}'
$Repo = '{repo}'
if (-not (Test-Path $Repo)) {{ Write-Host "NOVA3 worker: source checkout missing at $Repo"; exit 2 }}
$code = 'import sys; sys.path.insert(0, sys.argv[1]); from tools.dsh_loop import cli; raise SystemExit(cli.launcher_main(sys.argv[2], sys.argv[3:]))'
& python $code $Repo $Spec @args
exit $LASTEXITCODE
"""


def windows_cmd_launcher_text(state_path: Path) -> str:
    checkout, config = spec_for(state_path)
    repo = checkout or str(REPO)
    spec_file = Path(config).with_suffix(".spec.json")
    try:
        spec_file.parent.mkdir(parents=True, exist_ok=True)
        spec_file.write_text(json.dumps([checkout, config]) + "\n", encoding="utf-8")
    except OSError:
        pass
    code = ("import sys,json; sys.path.insert(0, sys.argv[1]); "
            "from tools.dsh_loop import cli; "
            "raise SystemExit(cli.launcher_main(json.load(open(sys.argv[2], encoding='utf-8')), sys.argv[3:]))")
    return (
        "@echo off\r\n"
        "rem NOVA3 reconstruction worker -- generated by tools/dsh_loop. Safe to delete.\r\n"
        f"if not exist \"{repo}\" ( echo NOVA3 worker: source checkout missing at {repo} & pause & exit /b 2 )\r\n"
        f"python -c \"{code}\" \"{repo}\" \"{spec_file}\" %*\r\n"
        "if errorlevel 1 if \"%~1\"==\"\" pause\r\n"
    )


def config_for_checkout(checkout: Path | None = None) -> Path:
    """The config that belongs to a checkout (its own .local/dsh/worker.json).

    Each checkout is an independent worker: its runtime lives in
    ``<checkout>/.local/dsh`` and so does its config.  The machine-wide config
    is only a fallback for checkouts that have never run setup.
    """
    checkout = Path(checkout or REPO)
