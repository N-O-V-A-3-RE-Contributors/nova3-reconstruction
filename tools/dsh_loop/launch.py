def status_text(state: dict, *, config_path: Path | None = None, check_key: bool = True) -> str:
    """Human-readable status. Never prints key material, only its fingerprint."""
    lines = [
        "NOVA3 DeepSeek Harness loop -- installation status",
        "  host:      " + resource.describe(),
        "  provider:  " + str(state.get("provider") or "(not configured)"),
        "  model:     " + str(state.get("model") or "(not configured)"),
        "  key ref:   " + str(state.get("api_key_env") or "(not configured)"),
    ]
    provider = state.get("provider")
    if check_key and provider in credentials.PROVIDERS:
        st = credentials.key_status(provider)
        if st.present:
            lines.append(f"  api key:   set for this terminal ({st.fingerprint})")
        else:
            lines.append(f"  api key:   MISSING -- run 'nova3-dsh setup' or export {st.env_name}")
    lines += [
        "  runtime:   " + str(state.get("dsh_version") or "?") + " in " + str(state.get("install_root")),
        "  profile:   " + str(state.get("dsh_profile")) + " under " + str(state.get("dsh_home")),
        "  source:    " + str(state.get("workspace") or "(no checkout yet)"),
        "  config:    " + str(config_path or "(unknown)"),
        "  github:    " + str(state.get("github_login") or "(not signed in)"),
    ]
    if os.name == "nt":
        lines.append("  launchers: " + ", ".join(state.get("launcher_paths") or []))
    return "\n".join(lines)
